#!/usr/bin/env python3
"""Отбор тем для статей из собранной семантики Вордстата.

Главное, ради чего он существует: Вордстат отдаёт один и тот же интент
десятком формулировок — «как избавиться от тревожности», «как убрать
тревожность», «как снять тревожность», «как побороть тревожность».
Это не разные темы, а один запрос. Если отдать их писателям как есть,
получится десять статей, которые отбирают трафик друг у друга.

Скрипт сворачивает такие группы в одну тему — самую частотную — и
отсеивает склейки лемматизатора, клинику у детей и заведомо чужие темы.

Использование:
    python3 scripts/select_topics.py <сколько тем> [--skip файл1.csv,файл2.csv]
"""
import csv, re, sys, collections, argparse

PLAN = 'docs/seo/temy-plan-final.csv'

# --- интенты: разные глаголы, одна задача читателя -------------------------
ACT = {
 'справ':'УБРАТЬ','избавит':'УБРАТЬ','убрат':'УБРАТЬ','борот':'УБРАТЬ','поборот':'УБРАТЬ','снят':'УБРАТЬ',
 'снизит':'УБРАТЬ','победит':'УБРАТЬ','преодолет':'УБРАТЬ','перестат':'УБРАТЬ','выйти':'УБРАТЬ',
 'пережит':'ПЕРЕЖИТЬ','отпустит':'ПЕРЕЖИТЬ','вернут':'ВЕРНУТЬ',
 'повысит':'ПОВЫСИТЬ','поднят':'ПОВЫСИТЬ','полюбит':'ПОВЫСИТЬ',
 'понят':'ПОНЯТЬ','проявляет':'ПОНЯТЬ','выглядит':'ПОНЯТЬ',
 'ведут себя':'ВЕСТИ','вести себя':'ВЕСТИ',
 'простыми словами':'ОПРЕДЕЛЕНИЕ','что это такое':'ОПРЕДЕЛЕНИЕ',
 'причин':'ПРИЧИНЫ','признак':'ПРИЗНАКИ','вид':'ВИДЫ','тип':'ВИДЫ','этап':'ЭТАПЫ','стади':'ЭТАПЫ',
 'техник':'ТЕХНИКИ','упражнен':'ТЕХНИКИ','тест':'ТЕСТ',
}
ACT_WORDS = re.compile(
 r'справ\w*|избавит\w*|убрат\w*|борот\w*|поборот\w*|снят\w*|снизит\w*|победит\w*|преодолет\w*|перестат\w*'
 r'|выйти|пережит\w*|отпустит\w*|вернут\w*|повысит\w*|поднят\w*|полюбит\w*|понят\w*|проявляет\w*|выглядит'
 r'|ведут|вести|простым\w*|словам\w*|такое|причин\w*|признак\w*|виды|вид|типы|тип|этап\w*|стади\w*'
 r'|техник\w*|упражнен\w*|тест\w*|стать|себя')
# синонимы объектов: тревога и тревожность — одно, гнев и злость — одно
OBJ = {'тревожност':'тревог','тревог':'тревог','беспокойств':'тревог','страх':'страх','депресс':'депресс',
 'выгоран':'выгоран','самооцен':'самооцен','увер':'самооцен','привязанност':'привязанност','расстава':'расстава',
 'развод':'развод','ревност':'ревност','апати':'апати','тоск':'тоск','грус':'тоск','злост':'злость','гнев':'злость',
 'стыд':'стыд','психосоматик':'психосоматик','буллинг':'буллинг','невроз':'невроз','отношени':'отношени'}
STOP = set('как что это для в на с со и не при от до по у к о а но или же бы то так себя мне вы ты я мой свой'.split())

# --- что не берём в работу вообще ------------------------------------------
DROP = re.compile(
  r'прыщ|дермат|похуден|диет'                                  # чужая тема
  r'|школьный психолог испортил|как зовут психолог|как проходить психолог|тест на психолога'
  r'|как выглядит психолог|как вернуть психолог|как избавиться от психолог|как жить советы'
  r'|как подавлять эмоции'                                     # вредный совет
  r'|как начать депресс|как впасть|как заработать депресс'      # опасные запросы
  r'|^зачем расстава|без$|^как стать поднять|^как называется '  # склейки лемматизатора
  r'|^признаки (психолог|самооцен)|^причины паника'
  r'|(депресси|невроз|тревожн)\w*\s+у\s+(подростк|детей|ребенка)'   # клиника у детей
  r'|^\w+\s+симптомы|^симптомы\s+\w+(ия|ость|ка)$', re.I)

def intent(t):
    low = t.lower()
    act = next((v for k, v in ACT.items() if k in low), '')
    words = [w for w in re.findall(r'[а-яё]+', low)
             if w not in STOP and len(w) > 3 and not ACT_WORDS.fullmatch(w)]
    obj = sorted({next((v for k, v in OBJ.items() if w.startswith(k)), w[:6]) for w in words})
    return (act, tuple(obj))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('count', type=int)
    ap.add_argument('--skip', default='')
    ap.add_argument('--out', default='')
    a = ap.parse_args()

    used_intents, used_titles = set(), set()
    for f in filter(None, a.skip.split(',')):
        for r in csv.DictReader(open(f, encoding='utf-8')):
            used_intents.add(intent(r['тема'])); used_titles.add(r['тема'])

    QUOTA = {'Отношения':.18,'Словарь и термины':.18,'Тревога и депрессия':.13,'Для психологов':.11,
             'Дети и подростки':.11,'Эмоции и состояния':.11,'Выгорание и работа':.07,
             'Самооценка и личность':.06,'Тесты':.03,'Практики и восстановление':.02}
    CTA = {'Отношения':'/artterapy','Словарь и термины':'/artterapy','Тревога и депрессия':'/artterapy',
           'Для психологов':'/praktik','Дети и подростки':'/artterapy','Эмоции и состояния':'/artterapy',
           'Выгорание и работа':'/coach','Самооценка и личность':'/artterapy','Тесты':'/online',
           'Практики и восстановление':'/online'}

    by = collections.defaultdict(list)
    for r in csv.DictReader(open(PLAN, encoding='utf-8')):
        b = r['блок'].split(' →')[0]
        if b == 'Прочее (вычитать вручную)' or r['тема'] in used_titles or DROP.search(r['тема']): continue
        by[b].append(r)
    for b in by: by[b].sort(key=lambda x: -int(x['частота']))

    out = []
    for b, share in QUOTA.items():
        limit, cnt = round(a.count * share), 0
        for r in by.get(b, []):
            if cnt >= limit: break
            i = intent(r['тема'])
            if i in used_intents: continue      # тот же интент уже занят — пропускаем
            used_intents.add(i)
            out.append({'тема': r['тема'], 'ключ': r['ключ'], 'частота': int(r['частота']),
                        'блок': b, 'cta': CTA[b]})
            cnt += 1
    out.sort(key=lambda x: -x['частота'])
    if a.out:
        with open(a.out, 'w', encoding='utf-8', newline='') as fh:
            w = csv.DictWriter(fh, fieldnames=['№','тема','ключ','частота','блок','cta']); w.writeheader()
            for i, r in enumerate(out, 1): w.writerow({'№': i, **r})
    for i, r in enumerate(out, 1):
        print(f"{i}. {r['тема']} — {r['частота']} — {r['cta']}")
    print(f"\nотобрано {len(out)} тем без повторов интента", file=sys.stderr)

if __name__ == '__main__':
    main()
